-- Footebas: global coach ranking (docs/04, docs/09 decision 10, ADR 0013).
-- Only the API touches these tables, through its own database role; the
-- browser never reads or writes them, so RLS denies every client role.
-- No personal data: the display name is the coach name chosen in the game.

create schema if not exists footebas;

-- Server-validated achievements. The API inserts them in the same
-- transaction that commits the career save where they happened, so a rolled
-- back season end never leaves an achievement behind. Points are stamped
-- with the rules version in force when they were earned.
create table footebas.validated_achievements (
  id bigint generated always as identity primary key,
  career_id text not null,
  user_id text not null,
  display_name text not null check (char_length(display_name) between 1 and 80),
  type text not null check (type in (
    'league_title', 'cup_title', 'state_title', 'continental_title',
    'promotion', 'season_completed'
  )),
  season integer not null check (season > 0),
  -- Empty for achievements without a competition (season completed).
  competition_id text not null default '',
  club_id text not null,
  club_reputation integer not null check (club_reputation between 0 and 100),
  game_date date not null,
  points integer not null check (points >= 0),
  rise_points integer not null check (rise_points >= 0),
  rules_version text not null,
  recorded_at timestamptz not null default now(),
  unique (career_id, type, season, competition_id)
);
create index validated_achievements_user_idx
  on footebas.validated_achievements (user_id);
create index validated_achievements_recorded_idx
  on footebas.validated_achievements (recorded_at);

-- Leaderboard snapshots regenerated by the scheduled job (Cron Trigger) and
-- served by `GET /v1/rankings` with edge cache. `period` is `all` for the
-- global and rise scopes and `YYYY-MM` (UTC) for the monthly one.
create table footebas.ranking_snapshots (
  scope text not null check (scope in ('global', 'rise', 'monthly')),
  period text not null
    check (period = 'all' or period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  position integer not null check (position > 0),
  user_id text not null,
  career_id text not null,
  display_name text not null,
  points integer not null check (points > 0),
  generated_at timestamptz not null,
  primary key (scope, period, position),
  unique (scope, period, user_id)
);
create index ranking_snapshots_user_idx on footebas.ranking_snapshots (user_id);

alter table footebas.validated_achievements enable row level security;
alter table footebas.ranking_snapshots enable row level security;

revoke all on schema footebas from anon, authenticated;
revoke all on all tables in schema footebas from anon, authenticated;
