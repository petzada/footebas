// Regenerates the launch catalog from the immutable research Markdown.
// Usage: pnpm --filter @footebas/content generate
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCatalog } from '../src/build.js';

const CONTENT_VERSION = 'catalog-2026-07-v1';
const SNAPSHOT_DATE = '2026-07';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const read = (path: string) => readFileSync(join(root, path), 'utf8');

const configPath = 'tools/sim-lab/config/mvp-competitions.json';
const config = JSON.parse(read(configPath)) as {
  sources: Record<string, string>;
};
const glueFile = 'dados/elencos/forca-relativa-cola.md';
const files = Object.fromEntries(
  [...Object.values(config.sources), glueFile].map((path) => [
    path,
    read(path),
  ]),
);

const catalog = buildCatalog({
  contentVersion: CONTENT_VERSION,
  snapshotDate: SNAPSHOT_DATE,
  files,
  competitionConfig: config,
  glueFile,
});

const outDir = join(root, 'packages', 'content', 'src', 'generated');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'catalog-source.ts'),
  [
    '// Generated by packages/content/scripts/generate-catalog.ts — do not edit.',
    `// ${CONTENT_VERSION}: ${String(catalog.clubs.length)} clubs, ${String(catalog.players.length)} players.`,
    `export const CATALOG_SOURCE = ${JSON.stringify(JSON.stringify(catalog))};`,
    '',
  ].join('\n'),
);

const counts = new Map<string, number>();
for (const note of catalog.notes)
  counts.set(note.kind, (counts.get(note.kind) ?? 0) + 1);
const report = [
  `# Relatório do catálogo ${CONTENT_VERSION}`,
  '',
  `Gerado a partir de ${catalog.sources.map((source) => `\`${source}\``).join(', ')}.`,
  '',
  `- Clubes: ${String(catalog.clubs.length)}`,
  `- Jogadores: ${String(catalog.players.length)}`,
  `- Clubes [parcial]: ${String(catalog.clubs.filter(({ partial }) => partial).length)}`,
  '',
  '## Lacunas mantidas explícitas (nada foi inventado)',
  '',
  ...[...counts].map(([kind, count]) => `- \`${kind}\`: ${String(count)}`),
  '',
  '## Detalhe',
  '',
  '| Tipo | Sujeito | Origem |',
  '|---|---|---|',
  ...catalog.notes.map(
    (note) =>
      `| ${note.kind} | ${note.subject} | ${note.source.file}:${String(note.source.line)} |`,
  ),
  '',
].join('\n');
writeFileSync(join(root, 'packages', 'content', 'catalog-report.md'), report);
console.log(
  `catalog ${CONTENT_VERSION}: ${String(catalog.clubs.length)} clubs, ${String(catalog.players.length)} players, ${String(catalog.notes.length)} notes`,
);
