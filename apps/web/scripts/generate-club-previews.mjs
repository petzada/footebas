// Regenerates lib/club-previews.ts from the canonical launch catalog: every
// Brazilian league club (Séries A, B e C) with derived strength and the
// research-backed highlights. Run after the catalog changes:
//   pnpm --filter @footebas/content build && pnpm --filter @footebas/web clubs:generate
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadCatalog } from '../../../packages/content/dist/index.js';

const catalog = loadCatalog();
const GROUP = {
  GK: 'gk',
  CB: 'def',
  LB: 'def',
  RB: 'def',
  DM: 'mid',
  CM: 'mid',
  AM: 'mid',
  LW: 'att',
  RW: 'att',
  ST: 'att',
};
const DIVISION_LABEL = {
  'serie-a': 'Série A',
  'serie-b': 'Série B',
  'serie-c': 'Série C',
};
const ORDER = ['serie-a', 'serie-b', 'serie-c'];
const players = new Map(catalog.players.map((player) => [player.id, player]));

const clubs = catalog.clubs
  .filter((club) => club.origin === 'national' && club.division)
  .map((club) => {
    const squad = club.playerIds.map((id) => players.get(id)).filter(Boolean);
    const sorted = [...squad].sort(
      (a, b) => b.derived.strength - a.derived.strength,
    );
    const top = sorted.slice(0, 16);
    const strength = Math.round(
      top.reduce((sum, player) => sum + player.derived.strength, 0) /
        Math.max(1, top.length),
    );
    const groups = ['gk', 'def', 'mid', 'att'].map((group) => {
      const members = sorted.filter((p) => GROUP[p.position] === group);
      const highlights = [
        ...members.filter((p) => p.highlight?.level === 'craque'),
        ...members.filter((p) => p.highlight?.level === 'destaque'),
        ...members.filter((p) => !p.highlight),
      ]
        .slice(0, 2)
        .map((p) => ({
          name: p.name,
          position: p.position,
          strength: p.derived.strength,
          ...(p.highlight ? { level: p.highlight.level } : {}),
        }));
      return { group, count: members.length, highlights };
    });
    return {
      id: club.id,
      name: club.name,
      division: club.division,
      note: [DIVISION_LABEL[club.division], club.location]
        .filter(Boolean)
        .join(' · '),
      tier: club.tier,
      squadSize: squad.length,
      strength,
      groups,
    };
  })
  .sort(
    (a, b) =>
      ORDER.indexOf(a.division) - ORDER.indexOf(b.division) ||
      b.strength - a.strength ||
      a.name.localeCompare(b.name, 'pt-BR'),
  );

const target = fileURLToPath(
  new URL('../lib/club-previews.ts', import.meta.url),
);
writeFileSync(
  target,
  `// Generated by scripts/generate-club-previews.mjs from the launch catalog
// (${catalog.contentVersion}); do not edit by hand. Strength is derived (top-16
// average), never research data; highlights come from the research file.
import type { ClubPreview } from '@/lib/club-preview';

export const CLUB_PREVIEWS: readonly ClubPreview[] = ${JSON.stringify(clubs, null, 2)};
`,
);
console.log(`${String(clubs.length)} clubes gravados em ${target}`);
