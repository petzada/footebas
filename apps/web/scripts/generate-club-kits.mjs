/**
 * Derives each club's kit colours from its crest in `public/crests/` and
 * writes `lib/club-kits.generated.ts`.
 *
 *   pnpm --filter @footebas/web kits:generate
 *
 * The two most used saturated/neutral colours of the crest become the shirt
 * and the trim. Presentation only: the 3D match stage and club accents read
 * it; nothing in the game rules depends on it.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const sharp = require(
  require.resolve('sharp', {
    paths: [dirname(require.resolve('next/package.json'))],
  }),
);

const crests = resolve(here, '../public/crests');
const hex = ([r, g, b]) =>
  `#${[r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')}`;
const distance = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);

async function kitOf(file) {
  const { data, info } = await sharp(resolve(crests, file))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  /** Buckets of 32 levels per channel, weighted towards the crest centre. */
  const buckets = new Map();
  for (let y = 0; y < info.height; y += 1)
    for (let x = 0; x < info.width; x += 1) {
      const at = (y * info.width + x) * 4;
      if (data[at + 3] < 200) continue;
      const rgb = [data[at], data[at + 1], data[at + 2]];
      const key = rgb.map((v) => v >> 5).join(',');
      const entry = buckets.get(key) ?? { sum: [0, 0, 0], count: 0 };
      entry.sum[0] += rgb[0];
      entry.sum[1] += rgb[1];
      entry.sum[2] += rgb[2];
      entry.count += 1;
      buckets.set(key, entry);
    }
  const colours = [...buckets.values()]
    .map(({ sum, count }) => ({ rgb: sum.map((v) => v / count), count }))
    .sort((a, b) => b.count - a.count);
  if (colours.length === 0) return null;
  const luminance = ([r, g, b]) => 0.2126 * r + 0.7152 * g + 0.0722 * b;
  const saturation = ([r, g, b]) => Math.max(r, g, b) - Math.min(r, g, b);
  // Outlines are near-black: only a shirt colour when nothing else is there.
  const outline = (c) => luminance(c.rgb) < 28 && saturation(c.rgb) < 30;
  const pool = colours.filter((c) => !outline(c));
  const ranked = pool.length > 0 ? pool : colours;
  const total = ranked.reduce((sum, c) => sum + c.count, 0);
  // Prefer a saturated colour when it holds a fair share of the crest.
  const primary =
    ranked.find((c) => saturation(c.rgb) > 60 && c.count / total > 0.12) ??
    ranked[0];
  // The second colour must hold a real share of the crest: thin anti-aliased
  // blends between two colours never dress a kit. Black counts here.
  const whole = colours.reduce((sum, c) => sum + c.count, 0);
  const secondary = colours.find(
    (c) =>
      c !== primary &&
      c.count / whole >= 0.07 &&
      distance(c.rgb, primary.rgb) > 110,
  );
  const fallback =
    luminance(primary.rgb) > 140 ? [18, 22, 28] : [244, 244, 240];
  return [hex(primary.rgb), hex(secondary?.rgb ?? fallback)];
}

const entries = [];
for (const file of readdirSync(crests)
  .filter((name) => name.endsWith('.png'))
  .sort()) {
  const kit = await kitOf(file);
  if (kit) entries.push([file.replace(/\.png$/, ''), kit]);
}

const body = entries
  .map(
    ([id, [primary, secondary]]) => `  ${id}: ['${primary}', '${secondary}'],`,
  )
  .join('\n');
writeFileSync(
  resolve(here, '../lib/club-kits.generated.ts'),
  `// Generated by scripts/generate-club-kits.mjs from public/crests. Do not edit.\n` +
    `export const CREST_KITS: Readonly<Record<string, readonly [string, string]>> = {\n${body}\n};\n`,
);
console.log(`club-kits.generated.ts: ${entries.length} clubs`);
